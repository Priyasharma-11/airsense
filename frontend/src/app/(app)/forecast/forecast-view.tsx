"use client";

import { useQuery, useQueryClient } from "@tanstack/react-query";
import { BrainCircuit, CalendarClock, Info, RefreshCw, ShieldAlert, Sparkles, Sun } from "lucide-react";
import Link from "next/link";
import { useRouter, useSearchParams } from "next/navigation";
import { useMemo, useState } from "react";
import { toast } from "sonner";
import { axis, baseOption, EChart, useChartTokens } from "@/components/charts/echart";
import { HistoryForecastChart } from "@/components/charts/history-forecast-chart";
import { StationSelect } from "@/components/aq/widgets";
import { AqiBadge, Badge, Button, Card, CardHeader, ChartSkeleton, ErrorState, PageHeader, Segmented, Skeleton, Stat } from "@/components/ui/primitives";
import { api } from "@/lib/api";
import { categoryColor, cn, fmt, shortStation } from "@/lib/format";
import { usePreferences, useStations } from "@/lib/hooks";

const HORIZONS = [{ value: 6, label: "6 h" }, { value: 12, label: "12 h" }, { value: 24, label: "24 h" }];
const EXPLAIN = [{ value: "1", label: "+1 h" }, { value: "6", label: "+6 h" }, { value: "12", label: "+12 h" }, { value: "24", label: "+24 h" }];

export function ForecastView() {
  const t = useChartTokens();
  const qc = useQueryClient();
  const router = useRouter();
  const params = useSearchParams();
  const stations = useStations();
  const prefs = usePreferences();
  const [chosenStation, setStation] = useState<number | undefined>(Number(params.get("station")) || undefined);
  const [horizon, setHorizon] = useState(24);
  const [chosenThreshold, setThreshold] = useState<number>();
  const [explainH, setExplainH] = useState("24");
  // Derived defaults: URL > user preference > first model station; user threshold preference > 60
  const station = chosenStation ?? prefs.data?.default_station_id ?? stations.data?.find((s) => s.used_in_model)?.id;
  const threshold = chosenThreshold ?? prefs.data?.pm25_threshold ?? 60;
  const choose = (id: number) => { setStation(id); router.replace(`/forecast?station=${id}`, { scroll: false }); };

  const fc = useQuery({ queryKey: ["forecast", station, threshold], queryFn: () => api.forecast(station!, { threshold }), enabled: !!station, retry: false });
  const issued = fc.data?.issued_at;
  const hist = useQuery({ queryKey: ["history", station, "pm25", "hour", "48h", issued], enabled: !!issued,
    queryFn: () => api.history(station!, "pm25", "hour", new Date(new Date(issued!).getTime() - 72 * 3600_000).toISOString(), issued) });

  const pts = useMemo(() => (fc.data?.points ?? []).filter((p) => p.horizon <= horizon), [fc.data, horizon]);
  const stationInfo = stations.data?.find((s) => s.id === station);
  const contributions = fc.data?.explanations?.[explainH] ?? [];

  async function refresh() {
    try {
      const fresh = await api.forecast(station!, { threshold, refresh: true });
      qc.setQueryData(["forecast", station, threshold], fresh);
      toast.success("Forecast regenerated by the model");
    } catch (e) {
      toast.error((e as Error).message);
    }
  }

  return (
    <div>
      <PageHeader title="PM2.5 forecast" description="Direct multi-horizon XGBoost forecasts for the next 24 hours with split-conformal 80% prediction intervals and per-forecast explanations."
        actions={<>
          <StationSelect stations={stations.data} value={station} onChange={choose} />
          <Button variant="secondary" onClick={refresh} disabled={!fc.data} icon={<RefreshCw className="size-4" />}>Re-run</Button>
        </>} />

      {stationInfo && !stationInfo.used_in_model && (
        <div className="mb-4 flex items-start gap-2 rounded-[12px] border border-amber-200 bg-amber-50 px-4 py-3 text-[13px] text-amber-800 dark:border-amber-900 dark:bg-amber-950/30 dark:text-amber-300">
          <Info className="mt-0.5 size-4 shrink-0" />
          This station&apos;s PM2.5 coverage ({fmt.num(stationInfo.pm25_coverage_pct, 1)}%) was below the 70% threshold for training. The model is station-agnostic, so it still forecasts here, but accuracy was not validated at this site.
        </div>
      )}

      {fc.error ? <Card><ErrorState error={fc.error} onRetry={() => fc.refetch()} /></Card> : (
        <>
          <div className="grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
            {fc.isLoading ? [0, 1, 2, 3].map((i) => <Skeleton key={i} className="h-[118px] rounded-[16px]" />) : fc.data && <>
              <Stat label="Latest observed" value={fmt.num(fc.data.latest_pm25, 1)} unit="µg/m³" accent={categoryColor(fc.data.points[0]?.category)}
                hint={<>at {fmt.dateTime(fc.data.issued_at)}</>} icon={<CalendarClock className="size-4" />} />
              <Stat label={`Peak in next ${horizon} h`} value={fmt.num(Math.max(...pts.map((p) => p.pm25)), 1)} unit="µg/m³"
                accent={categoryColor(pts.reduce((a, b) => (b.pm25 > a.pm25 ? b : a), pts[0])?.category)}
                hint={<>around {fmt.time(pts.reduce((a, b) => (b.pm25 > a.pm25 ? b : a), pts[0])?.target_time)} IST</>} icon={<Sparkles className="size-4" />} />
              <Stat label={`Hours above ${threshold} µg/m³`} value={pts.filter((p) => p.pm25 > threshold).length} unit={`of ${pts.length}`}
                hint={`Max exceedance probability ${fmt.pct(Math.max(...pts.map((p) => p.p_exceed)))}`} icon={<ShieldAlert className="size-4" />} />
              <Stat label="Cleanest 2-hour window" value={fc.data.best_window ? `${fmt.time(fc.data.best_window.start)}` : "—"}
                unit={fc.data.best_window ? `– ${fmt.time(fc.data.best_window.end)}` : undefined}
                hint={fc.data.best_window ? <>≈ {fmt.num(fc.data.best_window.mean_pm25)} µg/m³ · best time to be outdoors</> : ""} icon={<Sun className="size-4" />} />
            </>}
          </div>

          <Card className="mt-4">
            <CardHeader title="Forecast with 80% prediction interval" icon={<Sparkles className="size-4" />}
              subtitle={fc.data ? <>Model <span className="font-mono text-[12px]">{fc.data.model_version}</span> · issued from the latest observation {fmt.dateTime(fc.data.issued_at)}</> : "…"}
              action={<div className="flex items-center gap-2">
                <label htmlFor="thr" className="text-[12px] text-muted">Threshold</label>
                <input id="thr" type="number" min={10} max={500} step={5} value={threshold} onChange={(e) => setThreshold(Math.min(500, Math.max(10, Number(e.target.value) || 60)))}
                  className="h-8 w-20 rounded-[8px] border border-line-strong bg-elevated px-2 text-[13px] tabular" />
                <Segmented size="sm" label="Horizon" value={horizon} onChange={setHorizon} options={HORIZONS} />
              </div>} />
            {fc.isLoading || hist.isLoading ? <ChartSkeleton height={340} /> :
              <div className="px-3 pb-3"><HistoryForecastChart height={340} history={hist.data} threshold={threshold}
                forecast={fc.data ? { ...fc.data, points: pts } : undefined} /></div>}
          </Card>

          <div className="mt-4 grid gap-4 xl:grid-cols-[1.1fr_1fr]">
            <Card>
              <CardHeader title="Exceedance probability" subtitle={`Probability PM2.5 exceeds ${threshold} µg/m³ each hour - calibrated on held-out validation residuals`} icon={<ShieldAlert className="size-4" />} />
              <div className="px-3 pb-3">
                {fc.data ? (
                  <EChart ariaLabel="Hourly exceedance probability bar chart" height={260} option={{
                    ...baseOption(t),
                    xAxis: axis(t, { type: "category", data: pts.map((p) => fmt.time(p.target_time)), splitLine: { show: false }, axisLabel: { color: t.text, fontSize: 10.5, interval: 2 } }),
                    yAxis: axis(t, { type: "value", max: 1, axisLabel: { color: t.text, formatter: (v: number) => `${v * 100}%` } }),
                    tooltip: { ...baseOption(t).tooltip, valueFormatter: (v: number) => `${(v * 100).toFixed(0)}%` },
                    series: [{ name: "P(exceed)", type: "bar", barMaxWidth: 16, data: pts.map((p) => ({ value: p.p_exceed,
                      itemStyle: { borderRadius: [4, 4, 0, 0], color: p.p_exceed >= 0.7 ? t.danger : p.p_exceed >= 0.4 ? "#ee8a3c" : t.brand } })),
                      markLine: { silent: true, symbol: "none", lineStyle: { color: t.muted, type: "dashed" }, label: { color: t.text, fontSize: 10, formatter: "50%" }, data: [{ yAxis: 0.5 }] } }],
                  }} />
                ) : <ChartSkeleton height={260} />}
              </div>
            </Card>

            <Card>
              <CardHeader title="Why this forecast?" subtitle="Top feature contributions (SHAP values from XGBoost) for the selected lead time" icon={<BrainCircuit className="size-4" />}
                action={<Segmented size="sm" label="Lead time" value={explainH} onChange={setExplainH} options={EXPLAIN} />} />
              <div className="px-5 pb-5">
                {!fc.data ? <Skeleton className="h-56" /> : (
                  <ul className="space-y-2">
                    {contributions.map((c) => {
                      const max = Math.max(...contributions.filter((x) => x.feature !== "_base").map((x) => Math.abs(x.contribution)), 1);
                      const base = c.feature === "_base";
                      return (
                        <li key={c.feature} className={cn("grid grid-cols-[1fr_120px_56px] items-center gap-3 text-[13px]", base && "mt-3 border-t border-line pt-3")}>
                          <span className="truncate text-fg" title={c.feature}>{c.label}{c.value !== null && <span className="ml-1.5 text-[11.5px] text-faint tabular">= {fmt.num(c.value, 1)}</span>}</span>
                          {base ? <span className="text-[11.5px] text-faint">starting point</span> : (
                            <span className="relative h-2 rounded-full bg-subtle">
                              <span className="absolute top-0 h-2 rounded-full" style={{ width: `${(Math.abs(c.contribution) / max) * 50}%`, left: c.contribution >= 0 ? "50%" : `${50 - (Math.abs(c.contribution) / max) * 50}%`, background: c.contribution >= 0 ? t.danger : t.brand }} />
                              <span className="absolute left-1/2 top-[-3px] h-[14px] w-px bg-line-strong" />
                            </span>
                          )}
                          <span className={cn("text-right font-medium tabular", base ? "text-fg" : c.contribution >= 0 ? "text-red-600 dark:text-red-400" : "text-brand-600")}>{c.contribution >= 0 && !base ? "+" : ""}{c.contribution.toFixed(1)}</span>
                        </li>
                      );
                    })}
                  </ul>
                )}
                <p className="mt-4 text-[12px] text-faint">Red pushes the forecast up, teal pulls it down (µg/m³). <Link href="/models" className="text-brand-600 hover:underline">How accurate is the model? →</Link></p>
              </div>
            </Card>
          </div>

          <Card className="mt-4">
            <CardHeader title="Hourly forecast table" subtitle="Lower and upper bounds of the 80% interval" />
            <div className="overflow-x-auto px-2 pb-2">
              <table className="w-full min-w-[620px] text-[13px]">
                <thead><tr className="text-left text-[11.5px] uppercase tracking-wide text-faint">
                  <th className="px-3 py-2">Time (IST)</th><th className="px-3 py-2">Lead</th><th className="px-3 py-2 text-right">PM2.5</th><th className="px-3 py-2 text-right">80% interval</th><th className="px-3 py-2">Category</th><th className="px-3 py-2 text-right">P(&gt;{threshold})</th>
                </tr></thead>
                <tbody>
                  {pts.map((p) => (
                    <tr key={p.horizon} className="border-t border-line">
                      <td className="px-3 py-2 tabular">{fmt.dateTime(p.target_time)}</td>
                      <td className="px-3 py-2 text-muted">+{p.horizon} h</td>
                      <td className="px-3 py-2 text-right font-semibold tabular">{p.pm25.toFixed(1)}</td>
                      <td className="px-3 py-2 text-right text-muted tabular">{p.lower.toFixed(0)} – {p.upper.toFixed(0)}</td>
                      <td className="px-3 py-2"><AqiBadge category={p.category} /></td>
                      <td className="px-3 py-2 text-right tabular">{fmt.pct(p.p_exceed)}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </Card>
          {stationInfo && <p className="mt-3 text-[12px] text-faint">Station: {stationInfo.name} ({stationInfo.provider}) · <Badge>{shortStation(stationInfo.name)}</Badge></p>}
        </>
      )}
    </div>
  );
}
