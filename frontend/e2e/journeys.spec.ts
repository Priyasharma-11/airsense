import { expect, test, type Page } from "@playwright/test";

const PASSWORD = "E2eTestPass1";

async function register(page: Page) {
  const email = `e2e-${Date.now()}-${Math.floor(Math.random() * 1e4)}@example.com`;
  await page.goto("/register");
  await page.getByLabel("Full name").fill("E2E Tester");
  await page.getByLabel("Email").fill(email);
  await page.locator("#password").fill(PASSWORD);
  await page.getByRole("button", { name: "Create account" }).click();
  await expect(page).toHaveURL(/\/dashboard/);
  return email;
}

test("landing page shows live data and the model-generated forecast", async ({ page }) => {
  await page.goto("/");
  await expect(page.getByRole("heading", { name: /Know Pune's air/ })).toBeVisible();
  await expect(page.getByText(/Live from \d+ Pune monitors/)).toBeVisible();
  await expect(page.getByText(/Generated by model v\d{8}-/)).toBeVisible();
  await expect(page.getByRole("img", { name: /24-hour forecast/ })).toBeVisible();
});

test("protected routes redirect to sign-in", async ({ page }) => {
  await page.goto("/forecast");
  await expect(page).toHaveURL(/\/login\?next=%2Fforecast/);
});

test("invalid login shows a server error", async ({ page }) => {
  await page.goto("/login");
  await page.getByLabel("Email").fill("nobody@example.com");
  await page.locator("#password").fill("WrongPass1");
  await page.getByRole("button", { name: "Sign in" }).click();
  await expect(page.getByRole("alert").filter({ hasText: "Incorrect email or password" })).toBeVisible();
});

test("full user journey: register → dashboard → forecast → alert → logout", async ({ page }) => {
  await register(page);

  // Dashboard: real backend data
  await expect(page.getByRole("heading", { name: "Pune air quality" })).toBeVisible();
  await expect(page.getByRole("img", { name: /^AQI \d+/ })).toBeVisible();
  await expect(page.getByRole("table")).toContainText("Katraj Dairy");

  // Forecast page via navigation; switching station updates the forecast
  await page.getByRole("link", { name: "Forecast" }).first().click();
  await expect(page.getByRole("heading", { name: "PM2.5 forecast" })).toBeVisible();
  await expect(page.getByRole("table")).toContainText("+24 h");
  await page.getByLabel("Monitoring station").selectOption({ label: "Katraj Dairy, Pune · MPCB" });
  await expect(page).toHaveURL(/station=\d+/);
  await expect(page.getByText(/Model v\d{8}-/).first()).toBeVisible();

  // Analytics filters
  await page.getByRole("link", { name: "Analytics" }).first().click();
  await expect(page.getByText("Which months have the highest PM2.5?")).toBeVisible();
  await page.getByRole("radio", { name: "90 days" }).click();
  await expect(page.getByRole("radio", { name: "90 days" })).toHaveAttribute("aria-checked", "true");

  // Map shows real station markers
  await page.getByRole("link", { name: "Geospatial" }).first().click();
  await expect(page.locator(".leaflet-interactive")).toHaveCount(10);
  await expect(page.getByText("Hotspot ranking")).toBeVisible();

  // Alerts: create rule, evaluate, see stored alert, delete rule with confirmation
  await page.getByRole("link", { name: /^Alerts/ }).first().click();
  await page.getByLabel("Name (optional)").fill("E2E rule");
  await page.getByLabel("Threshold (µg/m³)").fill("10");
  await page.getByRole("button", { name: "Create rule" }).click();
  await expect(page.getByText("E2E rule")).toBeVisible();
  await page.getByRole("button", { name: "Check rules now" }).click();
  await expect(page.getByText(/new alert/)).toBeVisible();
  await expect(page.getByText(/expected above 10 µg\/m³|above 10 µg\/m³ now/).first()).toBeVisible();
  await page.getByRole("button", { name: "Delete E2E rule" }).click();
  await expect(page.getByRole("dialog")).toContainText("Delete alert rule?");
  await page.getByRole("dialog").getByRole("button", { name: "Delete" }).click();
  await expect(page.getByText("Alert rule deleted")).toBeVisible();

  // Settings persist through the API
  await page.getByRole("link", { name: "Settings" }).click();
  await page.getByLabel("Personal PM2.5 threshold (µg/m³)").fill("45");
  await page.getByRole("button", { name: "Save preferences" }).click();
  await expect(page.getByText("Preferences saved")).toBeVisible();
  await page.reload();
  await expect(page.getByLabel("Personal PM2.5 threshold (µg/m³)")).toHaveValue("45");

  // Logout clears the session
  await page.getByRole("button", { name: "Sign out" }).click();
  await expect(page).toHaveURL(/\/login/);
  await page.goto("/dashboard");
  await expect(page).toHaveURL(/\/login/);
});

test("password reset flow (development mode)", async ({ page }) => {
  const email = await register(page);
  await page.getByRole("button", { name: "Sign out" }).click();
  await page.goto("/forgot-password");
  await page.getByLabel("Email").fill(email);
  await page.getByRole("button", { name: "Send reset link" }).click();
  await page.getByRole("link", { name: "Open the reset link" }).click();
  await page.getByLabel("New password").fill("BrandNew123");
  await page.getByLabel("Confirm password").fill("BrandNew123");
  await page.getByRole("button", { name: "Update password" }).click();
  await expect(page.getByRole("heading", { name: "Password updated" })).toBeVisible();
  await page.goto("/login");
  await page.getByLabel("Email").fill(email);
  await page.locator("#password").fill("BrandNew123");
  await page.getByRole("button", { name: "Sign in" }).click();
  await expect(page).toHaveURL(/\/dashboard/);
});

test("API failures surface as errors, not fake data", async ({ page }) => {
  await register(page);
  await page.route("**/api/v1/air-quality/current", (r) => r.fulfill({ status: 503, contentType: "application/json",
    body: JSON.stringify({ error: { code: "service_unavailable", message: "Database unavailable." }, request_id: "e2e" }) }));
  await page.reload();
  await expect(page.getByRole("alert").filter({ hasText: "Database unavailable." })).toBeVisible();
});
